def connect():
    if DATABASE_URL:
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError("Install the production requirements before using DATABASE_URL.") from exc
        raw = psycopg.connect(DATABASE_URL, row_factory=dict_row)
        return PostgresConnection(raw)
    DATA.mkdir(exist_ok=True)
    db = sqlite3.connect(DB)
    db.row_factory = sqlite3.Row
    db.execute("PRAGMA foreign_keys = ON")
    return db


class PostgresConnection:
    """Small adapter so the same parameterized queries work with SQLite and Postgres."""
    def __init__(self, raw):
        self.raw = raw

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type:
                self.raw.rollback()
            else:
                self.raw.commit()
        finally:
            self.raw.close()

    def execute(self, statement, params=()):
        if statement == "PRAGMA foreign_keys = ON":
            return None
        if statement == "BEGIN IMMEDIATE":
            statement = "BEGIN"
        return self.raw.execute(statement.replace("?", "%s"), params)


