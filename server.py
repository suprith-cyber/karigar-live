def password_hash(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode(), salt=salt, n=2**14, r=8, p=1)
    return salt.hex() + ":" + digest.hex()


def password_ok(password: str, saved: str) -> bool:
    try:
        salt_hex, digest_hex = saved.split(":", 1)
        digest = hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt_hex), n=2**14, r=8, p=1)
        return hmac.compare_digest(digest.hex(), digest_hex)
    except (ValueError, TypeError):
        return False


class Handler(BaseHTTPRequestHandler):
    server_version = "Karigar/1.0"

    def log_message(self, fmt, *args):
        print("%s - %s" % (self.address_string(), fmt % args))

    def send_json(self, status, value, extra_headers=None):
        body = json.dumps(value, ensure_ascii=False, default=lambda item: item.isoformat() if isinstance(item, (date, datetime)) else str(item)).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "strict-origin-when-cross-origin")
        self.send_header("X-Frame-Options", "DENY")
        self.send_header("Permissions-Policy", "camera=(), microphone=(self), geolocation=()")
        self.send_header("Content-Security-Policy", "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com data:; img-src 'self' data: https:; connect-src 'self' https://*.supabase.co; base-uri 'self'; object-src 'none'; frame-ancestors 'none'; form-action 'self'")
        if COOKIE_SECURE:
            self.send_header("Strict-Transport-Security", "max-age=31536000; includeSubDomains")
        if extra_headers:
            for key, val in extra_headers.items():
                self.send_header(key, val)
        self.end_headers()
        self.wfile.write(body)

    def body_json(self):
        length = int(self.headers.get("Content-Length", "0"))
        if length > MAX_BODY:
            raise ValueError("Request is too large (8 MB max).")
        raw = self.rfile.read(length)
        try:
            data = json.loads(raw or b"{}")
        except json.JSONDecodeError as exc:
            raise ValueError("Please send valid form data.") from exc
        if not isinstance(data, dict):
            raise ValueError("Invalid request data.")
        return data

    def session_user(self, db):
        raw = self.headers.get("Cookie", "")
        jar = cookies.SimpleCookie()
        try:
            jar.load(raw)
            token = jar[COOKIE].value
        except (KeyError, cookies.CookieError):
            return None
        key = hashlib.sha256(token.encode()).hexdigest()
        row = db.execute("SELECT u.* FROM sessions s JOIN users u ON u.id=s.user_id WHERE s.token_hash=? AND s.expires_at>?", (key, int(time.time()))).fetchone()
        return dict(row) if row else None

    def require_user(self, db, role=None):
        user = self.session_user(db)
        if not user:
            self.send_json(401, {"error": "Please sign in first."})
            return None
        if role and user["role"] != role:
            self.send_json(403, {"error": f"Please sign in as a {role}."})
            return None
        return user

    def do_GET(self):
        parsed = urlparse(self.path)
        path = unquote(parsed.path)
        if path == "/healthz":
            self.send_json(200, {"ok": True})
            return
        if path.startswith("/api/"):
            self.api_get(path)
            return
        if path.startswith("/uploads/"):
            self.serve_upload(path)
            return
        if path == "/auth.html":
            self.serve_file(ROOT / "auth.html")
            return
        if path in ("/", "/index.html"):
            self.serve_file(ROOT / "index.html")
            return
        if path in ("/styles.css", "/app.js"):
            self.serve_file(ROOT / path.lstrip("/"))
            return
        self.send_error(404)

    def api_get(self, path):
        with connect() as db:
            if path == "/api/me":
                user = self.session_user(db)
                self.send_json(200, {"user": self.public_user(user) if user else None})
            elif path == "/api/profile/contact":
                user = self.require_user(db, "artisan")
                if not user:
                    return
                profile = db.execute("SELECT phone,public_address,show_contact FROM users WHERE id=?", (user["id"],)).fetchone()
                self.send_json(200, {"contact": dict(profile)})
            elif path == "/api/products":
                rows = db.execute("""SELECT p.*, u.name AS seller_name, u.location AS seller_location, CASE WHEN u.show_contact THEN u.phone ELSE '' END AS seller_phone, CASE WHEN u.show_contact THEN u.public_address ELSE '' END AS seller_public_address
                    FROM products p JOIN users u ON u.id=p.seller_id WHERE p.is_active AND p.stock>0 ORDER BY p.created_at DESC, p.id DESC""").fetchall()
                self.send_json(200, {"products": [dict(r) for r in rows]})
            elif path.startswith("/api/products/"):
                product_id = self.path_id(path, "/api/products/")
                row = db.execute("""SELECT p.*, u.name AS seller_name, u.location AS seller_location, u.upi_id AS seller_upi_id, CASE WHEN u.show_contact THEN u.phone ELSE '' END AS seller_phone, CASE WHEN u.show_contact THEN u.public_address ELSE '' END AS seller_public_address
                    FROM products p JOIN users u ON u.id=p.seller_id WHERE p.id=? AND p.is_active=TRUE
                AND p.stock>0""", (product_id,)).fetchone()
                if row:
                    self.send_json(200, {"product": dict(row)})
                else:
                    self.send_json(404, {"error": "That product could not be found."})
            elif path in ("/api/orders", "/api/my-products"):
                user = self.require_user(db)
                if not user:
                    return
                if path == "/api/my-products":
                    if user["role"] != "artisan":
                        self.send_json(403, {"error": "Artisan account required."})
                        return
                    rows = db.execute("SELECT * FROM products WHERE seller_id=? ORDER BY created_at DESC", (user["id"],)).fetchall()
                    self.send_json(200, {"products": [dict(r) for r in rows]})
                elif user["role"] == "artisan":
                    rows = db.execute("""SELECT o.*, p.name AS product_name, b.name AS buyer_name, b.email AS buyer_email
                        FROM orders o JOIN products p ON p.id=o.product_id JOIN users b ON b.id=o.buyer_id
                        WHERE o.seller_id=? ORDER BY o.created_at DESC, o.id DESC""", (user["id"],)).fetchall()
                    self.send_json(200, {"orders": [dict(r) for r in rows]})
                else:
                    rows = db.execute("""SELECT o.*, p.name AS product_name, s.name AS seller_name
                        FROM orders o JOIN products p ON p.id=o.product_id JOIN users s ON s.id=o.seller_id
                        WHERE o.buyer_id=? ORDER BY o.created_at DESC, o.id DESC""", (user["id"],)).fetchall()
                    self.send_json(200, {"orders": [dict(r) for r in rows]})
            else:
                self.send_json(404, {"error": "Not found."})

    @staticmethod
    def path_id(path, prefix):
        try:
            return int(path[len(prefix):])
        except ValueError:
            return -1

    @staticmethod
    def public_user(user):
        return {k: user[k] for k in ("id", "name", "email", "role", "location", "upi_id")}

    def do_POST(self):
        path = urlparse(self.path).path
        if not path.startswith("/api/"):
            self.send_json(404, {"error": "Not found."})
            return
        if not self.same_origin_request():
            self.send_json(403, {"error": "Please submit this request from the Karigar website."})
            return
        if not self.headers.get("Content-Type", "").lower().startswith("application/json"):
            self.send_json(415, {"error": "This endpoint accepts JSON requests only."})
            return
        if path in ("/api/login", "/api/signup") and self.rate_limited(path, 8, 300):
            self.send_json(429, {"error": "Too many attempts. Please wait a few minutes and try again."})
            return
        try:
            data = self.body_json()
            with connect() as db:
                if path == "/api/signup":
                    self.signup(db, data)
                elif path == "/api/login":
                    self.login(db, data)
                elif path == "/api/logout":
                    self.logout(db)
                elif path == "/api/products":
                    self.create_product(db, data)
                elif path == "/api/products/visibility":
                    self.set_product_visibility(db, data)
                elif path == "/api/profile/upi":
                    self.save_upi_profile(db, data)
                elif path == "/api/profile/contact":
                    self.save_contact_profile(db, data)
                elif path == "/api/upi-orders":
                    self.create_upi_order(db, data)
                elif path == "/api/cod-orders":
                    self.create_cod_order(db, data)
                elif path == "/api/orders/payment-confirm":
                    self.confirm_upi_payment(db, data)
                elif path == "/api/orders/cod-confirm":
                    self.confirm_cod_payment(db, data)
                elif path == "/api/orders/status":
                    self.update_order_status(db, data)
                else:
                    self.send_json(404, {"error": "Not found."})
        except ValueError as exc:
            self.send_json(400, {"error": str(exc)})
        except sqlite3.IntegrityError:
            self.send_json(409, {"error": "That email is already registered, or the request conflicts with current stock."})
        except Exception as exc:
            if exc.__class__.__name__ in ("UniqueViolation", "ForeignKeyViolation", "CheckViolation"):
                self.send_json(409, {"error": "That email is already registered, or the request conflicts with current stock."})
                return
            print("Request failed:", repr(exc))
            self.send_json(500, {"error": "Something went wrong. Please try again."})

    def same_origin_request(self):
        origin = self.headers.get("Origin")
        if not origin:
            return not DATABASE_URL
        parsed = urlparse(origin)
        if parsed.netloc.lower() != self.headers.get("Host", "").lower():
            return False
        forwarded_proto = self.headers.get("X-Forwarded-Proto", "").split(",")[0].strip().lower()
        expected_scheme = "https" if COOKIE_SECURE or forwarded_proto == "https" else "http"
        return parsed.scheme.lower() == expected_scheme

    def rate_limited(self, key, limit, seconds):
        now = time.time()
        bucket = RATE_LIMITS[f"{self.client_address[0]}:{key}"]
        while bucket and bucket[0] < now - seconds:
            bucket.popleft()
        if len(bucket) >= limit:
            return True
        bucket.append(now)
        return False

    def signup(self, db, data):
        name = str(data.get("name", "")).strip()[:80]
        email = str(data.get("email", "")).strip().lower()[:254]
        password = str(data.get("password", ""))
        role = data.get("role")
        location = str(data.get("location", "")).strip()[:100]
        if len(name) < 2 or not re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+", email):
            raise ValueError("Enter your name and a valid email address.")
        if len(password) < 8:
            raise ValueError("Use a password with at least 8 characters.")
        if role not in ("artisan", "buyer"):
            raise ValueError("Choose an artisan or buyer account.")
        cur = db.execute("INSERT INTO users(name,email,password_hash,role,location) VALUES(?,?,?,?,?) RETURNING id", (name,email,password_hash(password),role,location))
        user = db.execute("SELECT * FROM users WHERE id=?", (cur.fetchone()["id"],)).fetchone()
        self.new_session(db, user)

    def login(self, db, data):
        email = str(data.get("email", "")).strip().lower()
        password = str(data.get("password", ""))
        row = db.execute("SELECT * FROM users WHERE email=?", (email,)).fetchone()
        if not row or not password_ok(password, row["password_hash"]):
            self.send_json(401, {"error": "Email or password didn’t match."})
            return
        self.new_session(db, row)

    def save_contact_profile(self, db, data):
        user = self.require_user(db, "artisan")
        if not user:
            return
        phone = str(data.get("phone", "")).strip()[:40]
        public_address = str(data.get("public_address", "")).strip()[:500]
        show_contact = data.get("show_contact") is True
        digits = re.sub(r"\D", "", phone)
        if phone and not 7 <= len(digits) <= 15:
            raise ValueError("Enter a valid mobile number with 7 to 15 digits.")
        if show_contact and not (phone or public_address):
            raise ValueError("Add a phone number or public business address before sharing contact details.")
        db.execute("UPDATE users SET phone=?,public_address=?,show_contact=? WHERE id=?", (phone, public_address, show_contact, user["id"]))
        self.send_json(200, {"ok": True, "show_contact": show_contact})

    def save_upi_profile(self, db, data):
        user = self.require_user(db, "artisan")
        if not user:
            return
        upi_id = str(data.get("upi_id", "")).strip()[:200]
        if upi_id and not re.fullmatch(r"[A-Za-z0-9._-]{2,128}@[A-Za-z0-9.-]{2,64}", upi_id):
            raise ValueError("Enter a valid UPI ID, such as name@bank.")
        db.execute("UPDATE users SET upi_id=? WHERE id=?", (upi_id, user["id"]))
        updated = db.execute("SELECT * FROM users WHERE id=?", (user["id"],)).fetchone()
        self.send_json(200, {"user": self.public_user(dict(updated))})

    def new_session(self, db, user):
        token = secrets.token_urlsafe(32)
        db.execute("INSERT INTO sessions(token_hash,user_id,expires_at) VALUES(?,?,?)", (hashlib.sha256(token.encode()).hexdigest(), user["id"], int(time.time()) + 60*60*24*14))
        secure = "; Secure" if COOKIE_SECURE else ""
        self.send_json(200, {"user": self.public_user(dict(user))}, {"Set-Cookie": f"{COOKIE}={token}; Path=/; HttpOnly; SameSite=Lax; Max-Age=1209600{secure}"})

    def logout(self, db):
        raw = self.headers.get("Cookie", "")
        jar = cookies.SimpleCookie()
        try:
            jar.load(raw)
            token = jar[COOKIE].value
            db.execute("DELETE FROM sessions WHERE token_hash=?", (hashlib.sha256(token.encode()).hexdigest(),))
        except (KeyError, cookies.CookieError):
            pass
        secure = "; Secure" if COOKIE_SECURE else ""
        self.send_json(200, {"ok": True}, {"Set-Cookie": f"{COOKIE}=; Path=/; HttpOnly; SameSite=Lax; Max-Age=0{secure}"})

