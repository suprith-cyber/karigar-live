        if changed.rowcount != 1:
            db.execute("UPDATE orders SET payment_status='Unavailable',status='Unavailable' WHERE id=?", (order_id,))
            self.send_json(409, {"error": "There is not enough stock left to confirm this order."})
            return
        db.execute("UPDATE orders SET payment_status='Paid (artisan confirmed)',status='New' WHERE id=?", (order_id,))
        self.send_json(200, {"ok": True})

